/// Specifies the operation performed during tallying.
#[derive(
    Debug,
    Display,
    EnumString,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Serialize,
    Deserialize,
    BorshSerialize,
    BorshDeserialize,
)]
pub enum TallyOperation {
    /// Process ballots to calculate candidate results and participation statistics.
    #[strum(serialize = "process-ballots-all")]
    #[serde(rename = "process-ballots-all")]
    ProcessBallotsAll,
    /// Aggregate results that have been processed in every area.
    #[strum(serialize = "aggregate-results")]
    #[serde(rename = "aggregate-results")]
    AggregateResults,
    /// Calculate participation statistics without candidate results.
    #[strum(serialize = "skip-candidate-results")]
    #[serde(rename = "skip-candidate-results")]
    SkipCandidateResults,
}

/// Specifies whether a tally operation is scoped to an area or a contest.
#[derive(Debug, Display)]
pub enum ScopeOperation {
    /// Operation for an area.
    Area(TallyOperation),
    /// Operation for a contest.
    Contest(TallyOperation),
}

