/// Represents the status of the keys ceremony execution.
#[derive(
    Display,
    Serialize,
    Deserialize,
    Debug,
    PartialEq,
    Eq,
    Clone,
    EnumString,
    Default,
)]
pub enum KeysCeremonyExecutionStatus {
    /// User can configure the ceremony at this step
    USER_CONFIGURATION,
    /// Process starts but the config message hasn't been added to the board.
    #[default]
    STARTED,
    /// Config message has been added to the board and trustees are working.
    IN_PROGRESS,
    /// Successful completion.
    SUCCESS,
    /// Ceremony was cancelled.
    CANCELLED,
}

