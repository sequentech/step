/// The certification sentence above the signature boxes. Only actions
/// that sign a PDF have one.
pub fn certification(wording: &PageWording, action: SigningAction) -> Option<&str> {
    wording.certify.get(&action).map(String::as_str)
}

/// The action whose signatures a report needs, when the rule asks for them.
pub fn report_signing_action(report_type: &ReportType) -> Option<SigningAction> {
    match report_type {
        ReportType::ELECTORAL_RESULTS => Some(SigningAction::GenerateElectionReturns),
        ReportType::INITIALIZATION_REPORT
        | ReportType::PARTICIPATION_REPORT
        | ReportType::MANUAL_VERIFICATION => Some(SigningAction::GenerateReports),
        // The activity logs are a zip of PDFs when generated for real: not
        // signed as a PDF yet (a known gap).
        ReportType::ACTIVITY_LOGS
        | ReportType::BALLOT_IMAGES
        | ReportType::BALLOT_RECEIPT
        | ReportType::CREDENTIALS => None,
    }
}

/// The page's texts for `action`, naming the organization.
pub fn signature_page_texts(
    wording: &PageWording,
    action: SigningAction,
    organization: &str,
) -> Option<SignaturePageTexts> {
    Some(SignaturePageTexts {
        title: fill(&wording.title, &[("organization", organization)]),
        certification: certification(wording, action)?.to_owned(),
    })
}

/// One box per signature, filled in the order people sign.
pub fn signature_field_specs(wording: &PageWording, signatures: u16) -> Vec<SignatureFieldSpec> {
    let total = signatures.to_string();
    (1..=signatures)
        .map(|n| {
            let n = n.to_string();
            SignatureFieldSpec {
                label: fill(&wording.signature, &[("n", &n)]),
                tooltip: fill(&wording.signature_of, &[("n", &n), ("total", &total)]),
            }
        })
        .collect()
}

/// The tenant's display name (`tenant.settings.display_name`), else its slug.
pub async fn organization_name(
    hasura_transaction: &Transaction<'_>,
    tenant_id: Uuid,
) -> anyhow::Result<String> {
    hasura_transaction
        .query_opt(
            "SELECT COALESCE(NULLIF(btrim(settings->>'display_name'), ''), slug)
             FROM sequent_backend.tenant WHERE id = $1",
            &[&tenant_id],
        )
        .await
        .context("Error reading the tenant's name")?
        .map(|row| row.try_get(0))
        .transpose()?
        .ok_or_else(|| anyhow!("There is no tenant {tenant_id}"))
}

/// The report with its signature page when the event's rule for `action`
/// needs signatures, else `None` (the report stays as it is). A report with
/// a signature page must not be password-encrypted: that would break the
/// signatures.
#[instrument(skip(hasura_transaction, pdf), err)]
pub async fn report_signature_page(
    hasura_transaction: &Transaction<'_>,
    tenant_id: Uuid,
    election_event_id: Uuid,
    action: SigningAction,
    pdf: &[u8],
) -> anyhow::Result<Option<Vec<u8>>> {
    let rule: SigningRule =
        effective_rule(hasura_transaction, tenant_id, election_event_id, action).await?;
    if !rule.is_required() {
        return Ok(None);
    }
    let organization = organization_name(hasura_transaction, tenant_id).await?;
    let wording = event_wording(hasura_transaction, tenant_id, election_event_id).await?;
    let texts = signature_page_texts(wording, action, &organization)
        .ok_or_else(|| anyhow!("A {action} request signs no PDF"))?;
    let base = append_signature_page(
        pdf,
        &signature_field_specs(wording, rule.required()),
        &texts,
    )
    .context("Error adding the signature page")?;
    Ok(Some(base))
}

/// What becomes of a generated report.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReportDelivery {
    /// Released as the report's document: encrypted when its policy says
    /// so, and mailed when it is a scheduled or a voter's report.
    Release { encrypt: bool, send_email: bool },
    /// Its action needs signatures: kept as a signing document only. It is
    /// not the report's document, not encrypted (that would break the
    /// signatures) and not mailed; the executed request releases the
    /// signed document.
    AwaitSignatures,
}

/// How a report is delivered: `needs_signatures` when it got its
/// signature page.
pub fn report_delivery(
    needs_signatures: bool,
    encrypt_configured: bool,
    send_email: bool,
) -> ReportDelivery {
    if needs_signatures {
        ReportDelivery::AwaitSignatures
    } else {
        ReportDelivery::Release {
            encrypt: encrypt_configured,
            send_email,
        }
    }
}

