/// Private documents in the object storage, like the reports.
#[derive(Debug, Clone, Copy, Default)]
pub struct S3RevisionStore;

#[async_trait]
impl RevisionStore for S3RevisionStore {
    async fn load(
        &self,
        hasura_transaction: &Transaction<'_>,
        tenant_id: Uuid,
        election_event_id: Uuid,
        document_id: Uuid,
    ) -> anyhow::Result<Vec<u8>> {
        let tenant_id = tenant_id.to_string();
        let document = get_document(
            hasura_transaction,
            &tenant_id,
            Some(election_event_id.to_string()),
            &document_id.to_string(),
        )
        .await?
        .ok_or_else(|| anyhow!("There is no document {document_id}"))?;
        let file = get_document_as_temp_file(&tenant_id, &document).await?;
        std::fs::read(file.path()).context("Error reading the document")
    }

    async fn store(
        &self,
        hasura_transaction: &Transaction<'_>,
        tenant_id: Uuid,
        election_event_id: Uuid,
        file_name: &str,
        content: &[u8],
    ) -> anyhow::Result<Uuid> {
        let (_temp_path, path, size) =
            write_into_named_temp_file(&content.to_vec(), "signed-revision-", ".pdf")?;
        let document = upload_and_return_document(
            hasura_transaction,
            &path,
            size,
            "application/pdf",
            &tenant_id.to_string(),
            Some(election_event_id.to_string()),
            file_name,
            None,
            false,
        )
        .await?;
        Uuid::parse_str(&document.id).context("The stored document's id is not a UUID")
    }

    async fn link(
        &self,
        hasura_transaction: &Transaction<'_>,
        tenant_id: Uuid,
        election_event_id: Uuid,
        document_id: Uuid,
    ) -> anyhow::Result<Option<DocumentLink>> {
        let (tenant_id, election_event_id, document_id) = (
            tenant_id.to_string(),
            election_event_id.to_string(),
            document_id.to_string(),
        );
        let Some(document) = get_document(
            hasura_transaction,
            &tenant_id,
            Some(election_event_id.clone()),
            &document_id,
        )
        .await?
        else {
            return Ok(None);
        };
        let url = get_document_url(
            hasura_transaction,
            &tenant_id,
            Some(&election_event_id),
            &document_id,
        )
        .await?;
        Ok(url.map(|url| DocumentLink {
            url,
            name: document.name,
        }))
    }
}

fn sha256_hex(bytes: &[u8]) -> String {
    hex::encode(Sha256::digest(bytes))
}

fn sha256_bytes(text: Option<&str>, what: &str) -> SigningResult<[u8; 32]> {
    let bytes = hex::decode(text.unwrap_or_default())
        .ok()
        .and_then(|bytes| <[u8; 32]>::try_from(bytes).ok())
        .ok_or_else(|| anyhow!("The prepared revision's {what} is not a SHA-256"))?;
    Ok(bytes)
}

/// How a PAdES failure is answered: a stale revision is prepared again, a
/// signature or revision that doesn't match is refused (`signature`).
fn pades_failure(error: PadesError) -> SigningError {
    match error {
        PadesError::StaleRevision => SigningError::StaleRevision(
            "Another signature came first: prepare the document again.".into(),
        ),
        PadesError::RevisionMismatch
        | PadesError::CmsVerification(_)
        | PadesError::CmsTooLarge { .. } => SigningError::Refused {
            check: CertificateCheckId::Signature,
            message: format!("The PDF signature was refused: {error}"),
            other_holder: None,
        },
        PadesError::FieldNotFound(name) => SigningError::invalid(
            InvalidReason::DocumentFields,
            format!(
                "The document has no signature field {name} for this signature: generate it again."
            ),
        ),
        other => SigningError::Internal(anyhow!(other)),
    }
}

/// A revision's bytes, which must be the ones it records.
async fn load_revision(
    hasura_transaction: &Transaction<'_>,
    store: &dyn RevisionStore,
    revision: &DocumentRevisionRow,
) -> SigningResult<Vec<u8>> {
    let document_id = revision
        .document_id
        .ok_or_else(|| anyhow!("Revision {} has no document", revision.revision))?;
    let bytes = store
        .load(
            hasura_transaction,
            revision.tenant_id,
            revision.election_event_id,
            document_id,
        )
        .await?;
    if sha256_hex(&bytes) != revision.sha256 {
        return Err(SigningError::Internal(anyhow!(
            "Revision {} of request {} is not the document it records",
            revision.revision,
            revision.request_id
        )));
    }
    Ok(bytes)
}

/// Refuses a document whose reading needs more than reading the request.
async fn check_document_access(
    hasura_transaction: &Transaction<'_>,
    request: &SigningRequestRow,
    document_id: Uuid,
) -> SigningResult<()> {
    if signing_document_access_restricted(
        hasura_transaction,
        request.tenant_id,
        request.election_event_id,
        document_id,
    )
    .await?
    {
        return Err(SigningError::invalid(
            InvalidReason::Document,
            "This document is password-protected or holds voter secrets: it can't be signed.",
        ));
    }
    Ok(())
}

/// The request's own document's bytes, checked against `document_sha256`.
async fn load_request_document(
    hasura_transaction: &Transaction<'_>,
    store: &dyn RevisionStore,
    request: &SigningRequestRow,
) -> SigningResult<Vec<u8>> {
    let (Some(document_id), Some(sha256)) = (request.document_id, &request.document_sha256) else {
        return Err(SigningError::invalid(
            InvalidReason::Document,
            format!("Signing request {} has no PDF to sign.", request.code),
        ));
    };
    check_document_access(hasura_transaction, request, document_id).await?;
    let bytes = store
        .load(
            hasura_transaction,
            request.tenant_id,
            request.election_event_id,
            document_id,
        )
        .await?;
    if sha256_hex(&bytes) != *sha256 {
        return Err(SigningError::Internal(anyhow!(
            "The document of request {} is not the one it signs",
            request.id
        )));
    }
    Ok(bytes)
}

/// The document's latest revision, recording the request's own document as
/// its base revision the first time. The base must have one empty
/// signature field per signature the request needs. `base` is the
/// document's bytes when the caller already has them (they are used only
/// when their SHA-256 is the request's `document_sha256`). Call it holding
/// the request's lock (or in the transaction that created the request).
#[instrument(skip_all, fields(request_id = %request.id), err)]
pub async fn ensure_base_revision(
    hasura_transaction: &Transaction<'_>,
    store: &dyn RevisionStore,
    request: &SigningRequestRow,
    base: Option<&[u8]>,
) -> SigningResult<DocumentRevisionRow> {
    if let Some(latest) = get_latest_document_revision(
        hasura_transaction,
        request.tenant_id,
        request.election_event_id,
        request.id,
        RevisionLock::ForUpdate,
    )
    .await?
    {
        return Ok(latest);
    }
    let (Some(document_id), Some(sha256)) = (request.document_id, &request.document_sha256) else {
        return Err(SigningError::invalid(
            InvalidReason::Document,
            format!("Signing request {} has no PDF to sign.", request.code),
        ));
    };
    let bytes = match base {
        Some(bytes) if sha256_hex(bytes) == *sha256 => {
            check_document_access(hasura_transaction, request, document_id).await?;
            bytes.to_vec()
        }
        _ => load_request_document(hasura_transaction, store, request).await?,
    };
    let fields = signature_fields(&bytes).map_err(pades_failure)?;
    let empty = fields.iter().filter(|field| !field.signed).count();
    let needed = usize::try_from(request.required).unwrap_or_default();
    if fields.len() != needed || empty != needed {
        return Err(SigningError::invalid(
            InvalidReason::DocumentFields,
            format!(
                "The document has {empty} empty signature fields of {}; signing request {} needs {needed}. Generate the document again.",
                fields.len(),
                request.code,
            ),
        ));
    }
    Ok(insert_document_revision(
        hasura_transaction,
        &NewDocumentRevision {
            tenant_id: request.tenant_id,
            election_event_id: request.election_event_id,
            request_id: request.id,
            document_id: Some(document_id),
            sha256: sha256.clone(),
            state: DocumentRevisionState::Base,
            prepared_for_user: None,
            byte_range: None,
            field_index: None,
            parent_sha256: None,
            digest_sha256: None,
            appearance: None,
        },
    )
    .await?)
}

