/// What a signature's appearance tells of it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SignatureFacts<'a> {
    /// The certificate's holder (its CN).
    pub certificate_name: &'a str,
    /// The account's display name.
    pub display_name: &'a str,
    /// The signer's title ("Chairperson"), when the directory has one.
    pub title: Option<&'a str>,
    /// The CN of the certificate's issuer.
    pub issuer: Option<&'a str>,
    pub signing_time: DateTime<Utc>,
    /// The event's time zone; UTC without one.
    pub zone: Option<Tz>,
    /// The request's signing code.
    pub code: &'a str,
    /// The SHA-256 of the document before any signature (the base
    /// revision, the request's `document_sha256`).
    pub document_sha256: Option<&'a str>,
}

/// The visible lines of a signature: the certificate's holder, the
/// account's display name when it says something else, the signer's title,
/// when (ISO date and 24-hour time in `zone`, else UTC, with the zone's
/// name), the certificate's issuer, the signing code and the document's
/// SHA-256 before signatures.
pub fn appearance_lines(wording: &PageWording, facts: &SignatureFacts<'_>) -> Vec<String> {
    fn present(text: Option<&str>) -> Option<&str> {
        text.map(str::trim).filter(|text| !text.is_empty())
    }
    let time = match facts.zone {
        Some(zone) => format!(
            "{} {}",
            facts
                .signing_time
                .with_timezone(&zone)
                .format("%Y-%m-%d %H:%M:%S"),
            zone.name()
        ),
        None => facts
            .signing_time
            .format("%Y-%m-%d %H:%M:%S UTC")
            .to_string(),
    };
    let certificate_name = facts.certificate_name.trim();
    let mut lines = vec![fill(&wording.signed_by, &[("name", certificate_name)])];
    if facts.display_name.trim() != certificate_name {
        lines.push(facts.display_name.trim().to_owned());
    }
    if let Some(title) = present(facts.title) {
        lines.push(title.to_owned());
    }
    lines.push(fill(&wording.date, &[("time", &time)]));
    if let Some(issuer) = present(facts.issuer) {
        lines.push(fill(&wording.issuer, &[("issuer", issuer)]));
    }
    lines.push(fill(&wording.code, &[("code", facts.code)]));
    if let Some(sha256) = present(facts.document_sha256) {
        lines.push(fill(&wording.document, &[("sha256", sha256)]));
    }
    lines
}

/// The event's time zone: the one its monitoring settings name, if any.
async fn event_time_zone(
    hasura_transaction: &Transaction<'_>,
    tenant_id: Uuid,
    election_event_id: Uuid,
) -> anyhow::Result<Option<Tz>> {
    let event = EventRef {
        tenant_id,
        election_event_id,
    };
    let zone = get_live_config(hasura_transaction, event)
        .await?
        .and_then(|config| config.assembled.set.settings)
        .map(|settings| settings.time_zone);
    Ok(zone.and_then(|zone| match zone.parse() {
        Ok(zone) => Some(zone),
        Err(_) => {
            warn!("The event's time zone {zone:?} is unknown; signatures print UTC");
            None
        }
    }))
}

