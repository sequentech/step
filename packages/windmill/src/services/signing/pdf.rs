/// The visible lines of a signature: the certificate's holder, the
/// account's display name when it says something else, when (in `zone`,
/// else UTC) and the signing code.
pub fn appearance_lines(
    certificate_name: &str,
    display_name: &str,
    signing_time: DateTime<Utc>,
    zone: Option<Tz>,
    code: &str,
) -> Vec<String> {
    let time = match zone {
        Some(zone) => format!(
            "{} {}",
            signing_time
                .with_timezone(&zone)
                .format("%Y-%m-%d %H:%M:%S"),
            zone.name()
        ),
        None => signing_time.format("%Y-%m-%d %H:%M:%S UTC").to_string(),
    };
    let mut lines = vec![format!("Digitally signed by {certificate_name}")];
    if display_name.trim() != certificate_name.trim() {
        lines.push(display_name.to_owned());
    }
    lines.push(format!("Date: {time}"));
    lines.push(format!("Signing code: {code}"));
    lines
}

/// The event's time zone: the one its monitoring settings name, if any.
async fn event_time_zone(
    hasura_transaction: &Transaction<'_>,
    tenant_id: Uuid,
    election_event_id: Uuid,
) -> anyhow::Result<Option<Tz>> {
    let event = EventRef {
        tenant_id,
        election_event_id,
    };
    let zone = get_live_config(hasura_transaction, event)
        .await?
        .and_then(|config| config.assembled.set.settings)
        .map(|settings| settings.time_zone);
    Ok(zone.and_then(|zone| match zone.parse() {
        Ok(zone) => Some(zone),
        Err(_) => {
            warn!("The event's time zone {zone:?} is unknown; signatures print UTC");
            None
        }
    }))
}

