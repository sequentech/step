//! PDF signatures of signing requests (design §6), on top of
//! [`super::pades`].
//!
//! - At report generation, when the action's rule needs signatures,
//!   [`report_signature_page`] appends the signature page with one empty
//!   field per signature. That document is kept as a signing document
//!   only (never released, mailed or encrypted, see [`report_delivery`]);
//!   it is the request's, and its base revision ([`ensure_base_revision`]).
//! - [`prepare_pdf`]: a signer gets the ByteRange digest of the revision
//!   that fills the next empty field. What the revision is built from is
//!   kept; the revision itself is not. The same signer, certificate and
//!   parent revision get the same prepared revision again.
//! - On approval, [`PdfDocumentSigner`] rebuilds that revision on the
//!   latest one, under its row lock, checks the digest, verifies the CMS and
//!   keeps the signed revision. Another signer who went first makes the
//!   revision stale (409): the signer prepares again.
//! - [`latest_signed_document`] is the document as it stands, which an
//!   executed request releases.
//!
//! Election returns generated by the tally pipeline (velvet's
//! `generate_reports`, `post_tally`) don't pass through the report hook.
//!
//! The texts printed on the page are English, like the portal's
//! `signing.actions.<id>.certify` and `signing.signaturePage` strings.

