const HIDDEN = "\u2022\u2022\u2022"

/** The country calling code of an E.164 number, as digits. */
export const callingCode = (number: string): string | undefined => {
    const digits = number.trim().replace(/^\+/, "")
    return [1, 2, 3]
        .map((length) => digits.slice(0, length))
        .find((code) => CALLING_CODES.has(code))
}

/**
 * A destination as screens and records show it, like the backend's
 * `Destination::masked`: a number keeps its country code and last 3 digits,
 * an email its first 2 characters and its domain, a Page-scoped ID its last 3.
 */
export const maskDestination = (destination: string): string => {
    const value = destination.trim()
    const last3 = (text: string) => text.slice(Math.max(0, text.length - 3))
    const at = value.indexOf("@")
    if (at >= 0) {
        return `${value.slice(0, Math.min(2, at))}${HIDDEN}${HIDDEN}\u2022\u2022${value.slice(at)}`
    }
    if (value.startsWith("+")) {
        const digits = value.slice(1).replace(/[^\d]/g, "")
        const code = callingCode(digits) ?? ""
        return `+${code} ${HIDDEN} ${HIDDEN} ${last3(digits.slice(code.length))}`
    }
    return `${HIDDEN} ${last3(value)}`
}
